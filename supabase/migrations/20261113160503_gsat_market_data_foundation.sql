-- Supabase-managed extensions used by the GSAT validation/production collector.
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists supabase_vault with schema vault;
create extension if not exists pg_net with schema public;

create table public.gsat_market_candles (
  symbol text not null,
  timeframe text not null,
  candle_open timestamptz not null,
  open_price double precision not null,
  high_price double precision not null,
  low_price double precision not null,
  close_price double precision not null,
  volume double precision,
  tick_volume bigint,
  source text not null default 'BiQuote',
  first_ingested_at timestamptz not null default now(),
  last_ingested_at timestamptz not null default now(),
  constraint gsat_market_candles_pk primary key (symbol, timeframe, candle_open),
  constraint gsat_market_candles_symbol_check check (symbol = any (array['XAUUSD'::text, 'XAGUSD'::text])),
  constraint gsat_market_candles_timeframe_check check (timeframe = any (array['1m'::text, '15m'::text, '1h'::text, '4h'::text, '1d'::text])),
  constraint gsat_market_candles_source_check check (source = 'BiQuote'::text),
  constraint gsat_market_candles_open_price_check check (open_price > 0),
  constraint gsat_market_candles_high_price_check check (high_price > 0),
  constraint gsat_market_candles_low_price_check check (low_price > 0),
  constraint gsat_market_candles_close_price_check check (close_price > 0),
  constraint gsat_market_candles_ohlc_valid check (
    high_price >= greatest(open_price, close_price, low_price)
    and low_price <= least(open_price, close_price, high_price)
  ),
  constraint gsat_market_candles_volume_valid check (
    (volume is null or volume >= 0)
    and (tick_volume is null or tick_volume >= 0)
  )
);

create index gsat_market_candles_time_brin
  on public.gsat_market_candles using brin (candle_open)
  with (pages_per_range = 64);

comment on column public.gsat_market_candles.tick_volume is
  'BiQuote tick count, not exchange-traded volume or true volume-at-price.';

comment on column public.gsat_market_candles.candle_open is
  'UTC candle-open timestamp from the BiQuote OHLC feed.';

create table public.gsat_market_data_health (
  id smallint not null default 1,
  last_attempt_at timestamptz,
  last_success_at timestamptz,
  consecutive_failures integer not null default 0,
  status text not null default 'not_configured',
  last_error text,
  updated_at timestamptz not null default now(),
  latest_closed_1m_candle_at timestamptz,
  constraint gsat_market_data_health_pkey primary key (id),
  constraint gsat_market_data_health_id_check check (id = 1),
  constraint gsat_market_data_health_consecutive_failures_check check (consecutive_failures >= 0),
  constraint gsat_market_data_health_status_check check (
    status = any (array['not_configured'::text, 'healthy'::text, 'delayed'::text, 'degraded'::text, 'offline'::text])
  )
);

create table public.gsat_market_data_ingestion_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running',
  symbols text[] not null default array['XAUUSD'::text, 'XAGUSD'::text],
  timeframes text[] not null default array['1m'::text, '15m'::text, '1h'::text, '4h'::text, '1d'::text],
  api_requests integer not null default 0,
  fetched_count integer not null default 0,
  inserted_count integer not null default 0,
  updated_count integer not null default 0,
  rejected_count integer not null default 0,
  gap_count integer not null default 0,
  details jsonb not null default '{}'::jsonb,
  error_message text,
  constraint gsat_market_data_ingestion_runs_status_check check (
    status = any (array['running'::text, 'succeeded'::text, 'partial'::text, 'failed'::text])
  ),
  constraint gsat_market_data_ingestion_runs_api_requests_check check (api_requests >= 0),
  constraint gsat_market_data_ingestion_runs_fetched_count_check check (fetched_count >= 0),
  constraint gsat_market_data_ingestion_runs_inserted_count_check check (inserted_count >= 0),
  constraint gsat_market_data_ingestion_runs_updated_count_check check (updated_count >= 0),
  constraint gsat_market_data_ingestion_runs_rejected_count_check check (rejected_count >= 0),
  constraint gsat_market_data_ingestion_runs_gap_count_check check (gap_count >= 0)
);

create index gsat_market_data_ingestion_runs_started_idx
  on public.gsat_market_data_ingestion_runs using btree (started_at desc);

alter table public.gsat_market_candles enable row level security;
alter table public.gsat_market_data_health enable row level security;
alter table public.gsat_market_data_ingestion_runs enable row level security;

revoke all on table public.gsat_market_candles from anon, authenticated;
revoke all on table public.gsat_market_data_health from anon, authenticated;
revoke all on table public.gsat_market_data_ingestion_runs from anon, authenticated;

grant all on table public.gsat_market_candles to service_role;
grant all on table public.gsat_market_data_health to service_role;
grant all on table public.gsat_market_data_ingestion_runs to service_role;
grant usage, select on sequence public.gsat_market_data_ingestion_runs_id_seq to service_role;

insert into public.gsat_market_data_health (id, status)
values (1, 'not_configured')
on conflict (id) do nothing;
